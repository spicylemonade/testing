for card in cards:
    idx = card["id"]
    slug = card["symbolic_name"]
    folder = os.path.join(BASE, f"{idx:03d}_{slug}")
    os.makedirs(folder, exist_ok=True)
    
    # Write concept.json
    with open(os.path.join(folder, "concept.json"), "w") as f:
        json.dump(card, f, indent=2)
    
    # Write literature.json
    lit = literature.get(slug, [])
    with open(os.path.join(folder, "literature.json"), "w") as f:
        json.dump(lit, f, indent=2)
    
    # Write README.md
    domains_list = "\n".join(f"- {d}" for d in card["domains"])
    analogies = "\n".join(f"- {a}" for a in card["analogical_connections"])
    
    # Find related concepts from semantic bridge
    with open("/home/archivara/work/repo/results/concept_evolve/semantic_bridge.json") as f:
        bridge = json.load(f)
    related_concepts = []
    for edge in bridge["edges"]:
        if edge["source"] == slug:
            related_concepts.append(f"- **{edge['target']}**: {edge['relation']}")
        elif edge["target"] == slug:
            related_concepts.append(f"- **{edge['source']}**: {edge['relation']}")
    related = "\n".join(related_concepts) if related_concepts else "- (See semantic_bridge.json for connections)"
    
    verified = verified_results.get(slug, "- (Run analysis code to generate results)")
    
    readme = readme_template.format(
        title=slug.replace("_", " ").title(),
        id=idx,
        symbolic_name=slug,
        description=card["description"],
        domains_list=domains_list,
        math=card["mathematical_formalization"],
        analogies=analogies,
        impl=card["implementation_hypothesis"],
        exp=card["experiment_seed"],
        domain_count=len(card["domains"]),
        primary_domain=card["domains"][0],
        related=related,
        verified=verified,
    )
    
    with open(os.path.join(folder, "README.md"), "w") as f:
        f.write(readme)
    
    print(f"Created {folder}/")

