/*
 * base64_scalar.c - RFC 4648-compliant scalar Base64 decoder
 *
 * Reference baseline implementation. Processes one 4-character group at a time.
 * Supports both standard Base64 and Base64url variants.
 * Full validation of all input characters with descriptive error codes.
 */

