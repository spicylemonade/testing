base64_status_t base64_decode_scalar(
    const uint8_t *input,
    size_t input_len,
    uint8_t *output,
    size_t *output_len,
    base64_variant_t variant)
{
    if (!output_len) return BASE64_ERR_NULL;
    if (!input && input_len > 0) { *output_len = 0; return BASE64_ERR_NULL; }
    if (!output && input_len > 0) { *output_len = 0; return BASE64_ERR_NULL; }

    /* Empty input */
    if (input_len == 0) {
        *output_len = 0;
        return BASE64_OK;
    }

    const uint8_t *table = (variant == BASE64_URL) ? DECODE_TABLE_URL : DECODE_TABLE_STD;
    const size_t out_capacity = *output_len;

    /* Strip trailing padding to find actual data length */
    size_t data_len = input_len;
    size_t pad_count = 0;
    while (data_len > 0 && input[data_len - 1] == '=') {
        data_len--;
        pad_count++;
    }
    if (pad_count > 2) {
        *output_len = 0;
        return BASE64_ERR_PADDING;
    }

    /* Calculate expected output size */
    size_t total_chars = data_len;
    size_t full_groups = total_chars / 4;
    size_t remaining = total_chars % 4;

    /* Validate remaining characters count */
    if (remaining == 1) {
        /* A single trailing character cannot produce any output (need at least 2 for 1 byte) */
        *output_len = 0;
        return BASE64_ERR_LENGTH;
    }

    size_t expected_output = full_groups * 3;
    if (remaining == 2) expected_output += 1;
    else if (remaining == 3) expected_output += 2;

    if (out_capacity < expected_output) {
        *output_len = 0;
        return BASE64_ERR_OUTPUT;
    }

    size_t out_pos = 0;
    size_t i = 0;

    /* Process full 4-character groups */
    for (; i + 4 <= data_len; i += 4) {
        uint8_t a = table[input[i]];
        uint8_t b = table[input[i + 1]];
        uint8_t c = table[input[i + 2]];
        uint8_t d = table[input[i + 3]];

        /* Validate: any 0xFF means invalid character */
        if ((a | b | c | d) & 0x80) {
            *output_len = out_pos;
            return BASE64_ERR_INVALID;
        }

        output[out_pos++] = (uint8_t)((a << 2) | (b >> 4));
        output[out_pos++] = (uint8_t)(((b & 0x0F) << 4) | (c >> 2));
        output[out_pos++] = (uint8_t)(((c & 0x03) << 6) | d);
    }

    /* Process remaining characters (0, 2, or 3) */
    if (remaining >= 2) {
        uint8_t a = table[input[i]];
        uint8_t b = table[input[i + 1]];
        if ((a | b) & 0x80) {
            *output_len = out_pos;
            return BASE64_ERR_INVALID;
        }
        output[out_pos++] = (uint8_t)((a << 2) | (b >> 4));

        /* Check that unused bits in b are zero (canonical encoding) */
        if (remaining == 2 && (b & 0x0F) != 0) {
            /* Non-canonical: unused bits are non-zero. We decode anyway but could flag. */
        }

        if (remaining == 3) {
            uint8_t c = table[input[i + 2]];
            if (c & 0x80) {
                *output_len = out_pos;
                return BASE64_ERR_INVALID;
            }
            output[out_pos++] = (uint8_t)(((b & 0x0F) << 4) | (c >> 2));

            /* Check unused bits in c are zero */
            if ((c & 0x03) != 0) {
                /* Non-canonical encoding */
            }
        }
    }

    *output_len = out_pos;
    return BASE64_OK;
}
